/**
 * Основной указатель — мышь или палец.
 *
 * Разница не косметическая: на телефоне любое числовое поле выкидывает
 * системную клавиатуру на пол-экрана, и продавец теряет из виду то, что
 * вводит. Там вместо клавиатуры показываем свой цифровой блок. На компьютере
 * ничего заменять не нужно — физическая клавиатура быстрее любого блока.
 */
export function hasFinePointer(): boolean {
  try {
    return window.matchMedia('(pointer: fine)').matches
  } catch {
    return false // не смогли определить — считаем, что палец: так безопаснее
  }
}
